#!/usr/bin/env bash

set -euo pipefail

readonly CERT_DIR="/etc/nginx/certs"
readonly LETSENCRYPT_LIVE_DIR="/etc/letsencrypt/live"
readonly CERTBOT_HOOK_DIR="/etc/letsencrypt/renewal-hooks"
readonly CERTBOT_PRE_HOOK="${CERTBOT_HOOK_DIR}/pre/open-80.sh"
readonly CERTBOT_POST_HOOK="${CERTBOT_HOOK_DIR}/post/close-80.sh"
readonly CERTBOT_PORT_FLAG="/run/certbot-opened-80"

get_nginx_site_config_path() {
    local domain="$1"

    if [[ -d /etc/nginx/sites-available ]]; then
        echo "/etc/nginx/sites-available/${domain}.conf"
    else
        echo "/etc/nginx/conf.d/${domain}.conf"
    fi
}

get_nginx_site_link_path() {
    local domain="$1"

    if [[ -d /etc/nginx/sites-enabled ]]; then
        echo "/etc/nginx/sites-enabled/${domain}.conf"
    fi
}

check_domain_resolves() {
    local domain="$1"

    if getent ahosts "${domain}" >/dev/null 2>&1; then
        return 0
    fi

    return 1
}

install_cert_packages() {
    local packages=(nginx certbot python3-certbot-nginx openssl)
    local missing=()
    local pkg

    for pkg in "${packages[@]}"; do
        if ! dpkg -s "${pkg}" >/dev/null 2>&1; then
            missing+=("${pkg}")
        fi
    done

    if [[ ${#missing[@]} -eq 0 ]]; then
        log_info "nginx and certbot already installed"
        return 0
    fi

    log_info "Installing packages: ${missing[*]}"

    wait_for_apt_lock || return 1

    if ! apt-get update -qq 2>&1 | tee -a "${LOG_FILE}"; then
        log_warn "Failed to update package repositories, trying to install anyway"
    fi

    if ! DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${missing[@]}" 2>&1 | tee -a "${LOG_FILE}"; then
        log_error "Failed to install: ${missing[*]}"
        return 1
    fi

    log_info "Packages installed: ${missing[*]}"
    return 0
}

create_temporary_certificate() {
    local domain="$1"
    local crt="${CERT_DIR}/${domain}.crt"
    local key="${CERT_DIR}/${domain}.key"

    mkdir -p "${CERT_DIR}"

    if [[ -e "${crt}" && -e "${key}" ]]; then
        log_info "Certificate files already present: ${crt}"
        return 0
    fi

    log_info "Creating temporary self-signed certificate for ${domain}"

    rm -f "${crt}" "${key}"

    if ! (umask 077 && openssl req -x509 -nodes -newkey rsa:2048 -days 30 \
            -keyout "${key}" -out "${crt}" -subj "/CN=${domain}" >/dev/null 2>&1); then
        log_error "Failed to create self-signed certificate for ${domain}"
        return 1
    fi

    chmod 600 "${key}"
    chmod 644 "${crt}"

    log_info "Temporary certificate created: ${crt}"
    return 0
}

nginx_supports_http2_directive() {
    local version
    version="$(nginx -v 2>&1 | sed -n 's|.*nginx/\([0-9.]*\).*|\1|p')"

    if [[ -z "${version}" ]]; then
        return 1
    fi

    if [[ "$(printf '%s\n' "1.25.1" "${version}" | sort -V | head -n1)" == "1.25.1" ]]; then
        return 0
    fi

    return 1
}

write_nginx_site_config() {
    local domain="$1"
    local conf="$2"
    local webroot="/var/www/${domain}"
    local crt="${CERT_DIR}/${domain}.crt"
    local key="${CERT_DIR}/${domain}.key"

    local h2_listen=""
    local h2_line=""
    if nginx_supports_http2_directive; then
        h2_line="http2 on;"
    else
        h2_listen=" http2"
    fi

    mkdir -p "${webroot}"
    if [[ ! -e "${webroot}/index.html" ]]; then
        echo "<h1>${domain}</h1>" > "${webroot}/index.html"
    fi

    cat > "${conf}" <<EOF
# ${domain}: HTTP (:80) redirects to HTTPS, HTTPS + HTTP/2 (:443) serves the site.
# Generated by CoreServerKit server-init.sh

server {
    listen 80;
    listen [::]:80;
    server_name ${domain};

    return 301 https://\$host\$request_uri;
}

server {
    listen 443 ssl${h2_listen};
    listen [::]:443 ssl${h2_listen};
    ${h2_line}
    server_name ${domain};

    # Symlinks to ${LETSENCRYPT_LIVE_DIR}/${domain}/
    ssl_certificate     ${crt};
    ssl_certificate_key ${key};
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_ciphers         HIGH:!aNULL:!MD5;
    ssl_session_cache   shared:SSL:10m;
    ssl_session_timeout 1d;
    ssl_prefer_server_ciphers on;

    add_header Strict-Transport-Security "max-age=31536000" always;

    gzip on;
    gzip_vary on;
    gzip_min_length 256;
    gzip_proxied any;
    gzip_comp_level 5;
    gzip_types
        text/plain
        text/css
        text/javascript
        application/javascript
        application/json
        application/xml
        application/xml+rss
        application/manifest+json
        image/svg+xml;

    root  ${webroot};
    index index.html;

    # Add your own location / include directives here

    location / {
        try_files \$uri \$uri/ =404;
    }
}
EOF

    return 0
}

configure_nginx_site() {
    local domain="$1"
    local conf
    conf="$(get_nginx_site_config_path "${domain}")"
    local link
    link="$(get_nginx_site_link_path "${domain}")"

    if [[ -e "${conf}" ]]; then
        log_info "nginx config ${conf} already exists, leaving it untouched"
    else
        log_info "Writing nginx config: ${conf}"
        write_nginx_site_config "${domain}" "${conf}"

        if [[ -n "${link}" ]]; then
            ln -sf "${conf}" "${link}"
        fi

        if ! nginx -t 2>&1 | tee -a "${LOG_FILE}"; then
            rm -f "${conf}"
            if [[ -n "${link}" ]]; then
                rm -f "${link}"
            fi
            log_error "nginx rejected the config, ${conf} removed"
            return 1
        fi

        log_change "NGINX SITE CREATED: domain=${domain}, config=${conf}, root=/var/www/${domain}"
    fi

    return 0
}

reload_nginx() {
    if ! nginx -t 2>&1 | tee -a "${LOG_FILE}"; then
        log_error "nginx configuration test failed"
        return 1
    fi

    systemctl enable nginx >/dev/null 2>&1 || true

    if systemctl reload nginx 2>/dev/null || systemctl restart nginx 2>/dev/null; then
        log_info "nginx reloaded"
        return 0
    fi

    log_error "Failed to reload nginx"
    return 1
}

allow_https_port() {
    if ! command -v ufw >/dev/null 2>&1; then
        log_info "UFW not installed, skipping HTTPS firewall rule"
        return 0
    fi

    if ufw show added 2>/dev/null | grep -Eq "allow (443(/tcp)?|'?Nginx (Full|HTTPS)'?|'?WWW (Full|Secure)'?)( |$)"; then
        log_info "HTTPS port 443 already allowed in firewall"
        return 0
    fi

    log_info "Allowing HTTPS port 443 through firewall"
    if ! ufw allow 443/tcp comment 'HTTPS' >/dev/null; then
        log_error "Failed to allow 443/tcp in UFW"
        return 1
    fi

    log_change "UFW: allow=443/tcp (HTTPS)"
    return 0
}

install_certbot_port_hooks() {
    log_info "Installing certbot hooks to open port 80 during validation"

    mkdir -p "$(dirname "${CERTBOT_PRE_HOOK}")" "$(dirname "${CERTBOT_POST_HOOK}")"

    cat > "${CERTBOT_PRE_HOOK}" <<EOF
#!/bin/sh
# Opens port 80 in UFW for the ACME HTTP-01 challenge if it is closed,
# and remembers that it did so. Generated by CoreServerKit.
command -v ufw >/dev/null || exit 0
ufw status | grep -q '^Status: active' || exit 0
ufw status | grep -Eq '^(80(/tcp)?|Nginx (Full|HTTP)|WWW( Full)?) +ALLOW' && exit 0
ufw allow 80/tcp >/dev/null && touch ${CERTBOT_PORT_FLAG}
EOF

    cat > "${CERTBOT_POST_HOOK}" <<EOF
#!/bin/sh
# Closes port 80 only if it was opened by open-80.sh. Generated by CoreServerKit.
[ -e ${CERTBOT_PORT_FLAG} ] || exit 0
ufw delete allow 80/tcp >/dev/null
rm -f ${CERTBOT_PORT_FLAG}
EOF

    chmod 755 "${CERTBOT_PRE_HOOK}" "${CERTBOT_POST_HOOK}"

    log_info "certbot hooks installed: ${CERTBOT_PRE_HOOK}, ${CERTBOT_POST_HOOK}"
    return 0
}

close_certbot_port() {
    if [[ -x "${CERTBOT_POST_HOOK}" ]]; then
        "${CERTBOT_POST_HOOK}" || log_warn "Failed to close port 80, check: ufw status"
    fi
    return 0
}

issue_letsencrypt_certificate() {
    local domain="$1"
    local email="$2"

    local email_args=(--register-unsafely-without-email)
    if [[ -n "${email}" ]]; then
        email_args=(-m "${email}")
    fi

    log_info "Requesting Let's Encrypt certificate for ${domain}..."

    trap 'close_certbot_port; cleanup_on_exit' EXIT
    "${CERTBOT_PRE_HOOK}" || log_warn "Failed to open port 80, validation may fail"

    local rc=0
    certbot certonly --nginx -d "${domain}" \
        --non-interactive --agree-tos "${email_args[@]}" \
        --keep-until-expiring \
        --deploy-hook "systemctl reload nginx" 2>&1 | tee -a "${LOG_FILE}" || rc=$?

    close_certbot_port
    trap cleanup_on_exit EXIT

    if [[ "${rc}" -ne 0 ]]; then
        log_error "certbot failed for ${domain} (exit code ${rc})"
        return 1
    fi

    log_info "Certificate issued for ${domain}"
    return 0
}

link_letsencrypt_certificate() {
    local domain="$1"
    local live="${LETSENCRYPT_LIVE_DIR}/${domain}"

    if [[ ! -f "${live}/fullchain.pem" || ! -f "${live}/privkey.pem" ]]; then
        log_error "Let's Encrypt certificate not found in ${live}"
        return 1
    fi

    ln -sf "${live}/fullchain.pem" "${CERT_DIR}/${domain}.crt"
    ln -sf "${live}/privkey.pem" "${CERT_DIR}/${domain}.key"

    log_info "Linked ${CERT_DIR}/${domain}.{crt,key} -> ${live}/"
    return 0
}

enable_certbot_renewal() {
    local timer
    for timer in certbot.timer certbot-renew.timer; do
        if systemctl enable --now "${timer}" >/dev/null 2>&1; then
            log_info "Automatic renewal enabled: ${timer}"
            return 0
        fi
    done

    log_warn "certbot timer not found, add 'certbot renew -q' to cron"
    return 1
}

is_cert_configured() {
    local domain="$1"
    local fullchain="${LETSENCRYPT_LIVE_DIR}/${domain}/fullchain.pem"

    if [[ ! -f "${fullchain}" ]]; then
        return 1
    fi

    if [[ "$(readlink -f "${CERT_DIR}/${domain}.crt")" != "$(readlink -f "${fullchain}")" ]]; then
        return 1
    fi

    if [[ ! -f "$(get_nginx_site_config_path "${domain}")" ]]; then
        return 1
    fi

    return 0
}
